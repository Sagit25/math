#!/usr/bin/env python3
"""Generate the manuscript's result tables from experiment output.

Why this exists
---------------
The empirical claims of this thesis are unmeasured at the time of writing. The risk is
that someone later fills a plausible-looking number into a table by hand. This script
removes that path: ``paper/sections/08_results.tex`` only ever ``\\input``s files from
``paper/tables/``, and those files are only ever written by this script from the JSON
that ``cvdyn2dgs experiments`` produces.

Usage
-----
    # 1. produce measurements
    cvdyn2dgs experiments --out results --size small

    # 2. turn them into tables
    python scripts/make_tables.py results paper/tables

    # 3. clear the draft banner in paper/preamble.tex, then build
    cd paper && make

Running it with no results directory (or with a partial one) writes **stub** tables in
which every cell is ``\\NM`` - the conspicuous "not measured" marker. That is the state
the repository ships in.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

NM = r"\NM"

HEADER = (
    "%% AUTO-GENERATED by scripts/make_tables.py -- DO NOT EDIT BY HAND.\n"
    "%% Source: {source}\n"
    "%% Status: {status}\n"
)


def _fmt(value: Any, spec: str = ".3f") -> str:
    """Format a measured value, or emit the not-measured marker."""
    if value is None:
        return NM
    if isinstance(value, bool):
        return r"\checkmark" if value else r"$\times$"
    if isinstance(value, str):
        return value.replace("_", r"\_")
    try:
        f = float(value)
    except (TypeError, ValueError):
        return NM
    if f != f:  # NaN
        return NM
    return format(f, spec)


def _get(d: Any, *path: str, default: Any = None) -> Any:
    cur = d
    for key in path:
        if not isinstance(cur, dict) or key not in cur:
            return default
        cur = cur[key]
    return cur


def _write(out_dir: Path, name: str, body: str, *, source: str, measured: bool) -> None:
    status = "filled from measurements" if measured else "STUB - no measurements available"
    path = out_dir / f"{name}.tex"
    path.write_text(HEADER.format(source=source, status=status) + body, encoding="utf-8")
    print(f"  {'FILLED' if measured else 'stub  '}  {path}")


