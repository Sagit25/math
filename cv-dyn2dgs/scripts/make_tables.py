def table_external_status(res: dict, out: Path) -> None:
    """Which external comparisons exist, and which have actually been run.

    Generated from ``external/manifest.json`` so the table cannot drift from the pins,
    and marked measured only when a results file says a target was really executed.
    """
    manifest = Path(__file__).resolve().parent.parent / "external" / "manifest.json"
    targets: list[dict] = []
    if manifest.exists():
        targets = json.loads(manifest.read_text(encoding="utf-8")).get("targets", [])
    ran = _get(res, "comparison", "external", "data", "ran", default={}) or {}

    lines = []
    dagger = r"$\dagger$"
    for t in sorted(targets, key=lambda x: (x["layer"], x["key"])):
        code = "---" if not t.get("repo") else (
            t["commit"][:8] if t.get("commit") else "---"
        )
        vend = "" if t.get("redistributable") else dagger
        status = "실행됨" if t["key"] in ran else r"\NM"
        key = t["key"].replace("_", "\\_")
        layer = t["layer"]
        lines.append(
            "%d & \\texttt{%s}%s & \\texttt{%s} & %s \\\\" % (layer, key, vend, code, status)
        )

    body = r"""\begin{table}[htbp]
\centering\small
\caption{외부 비교군의 고정 commit과 실행 상태. commit은
\texttt{external/manifest.json}에서 자동 생성되므로 표와 고정값이 어긋날 수 없다.
$\dagger$는 라이선스상 본 저장소에 포함할 수 없는 대상(라이선스 파일이 없거나
Inria/MPII 연구 전용)이며, 고정 commit으로 필요할 때만 clone한다.}
\label{tab:external-status}
\begin{tabular}{@{}clll@{}}
\toprule
층위 & 대상 & 고정 commit & 상태 \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    _write(out, "external_status", body, source="external/manifest.json",
           measured=bool(ran))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("results", nargs="?", default="results",
                    help="directory written by `cvdyn2dgs experiments`")
    ap.add_argument("tables", nargs="?", default="paper/tables",
                    help="output directory for the .tex tables")
    args = ap.parse_args(argv)

    res_dir = Path(args.results)
    out_dir = Path(args.tables)
    out_dir.mkdir(parents=True, exist_ok=True)

    res: dict = {}
    combined = res_dir / "all_results.json"
    if combined.exists():
        res = json.loads(combined.read_text(encoding="utf-8"))
        print(f"loaded {combined}")
    else:
        # Fall back to individual files so partial runs still fill what they can.
        for key, fname in (
            ("theory_checks", "theory_checks.json"),
            ("baselines", "baselines.json"),
            ("research_questions", "research_questions.json"),
            ("ablations", "ablations.json"),
            ("spacing_ablation", "spacing_ablation.json"),
            ("progressive", "progressive.json"),
        ):
            p = res_dir / fname
            if p.exists():
                loaded = json.loads(p.read_text(encoding="utf-8"))
                if key == "baselines" and isinstance(loaded, dict):
                    loaded = loaded.get("headline", loaded)
                res[key] = loaded
                print(f"loaded {p}")
        if not res:
            print(f"no results found in {res_dir} -- writing stub tables", file=sys.stderr)

    print(f"writing tables to {out_dir}")
    table_kernel_checks(res, out_dir)
    table_theory_rates(res, out_dir)
    table_rq1(res, out_dir)
    table_rq2(res, out_dir)
    table_rq3(res, out_dir)
    table_rq4(res, out_dir)
    table_rq5(res, out_dir)
    table_rq6(res, out_dir)
    table_baselines(res, out_dir)
    table_ablations(res, out_dir)
    table_stages(res, out_dir)
    # External comparison design (paper sec. 7.3). These are stubs until someone with a
    # GPU actually runs the comparisons; external_status is generated from the manifest
    # so its commit column is always correct even when nothing has been run.
    table_surface_source(res, out_dir)
    table_free_geometry(res, out_dir)
    table_viewpoint(res, out_dir)
    table_external_status(res, out_dir)
    # Quality against cost. These are the two tables that answer "what did it cost to get
    # that quality, and is the trade-off real or is this configuration just worse?"
    table_cost_quality(res, out_dir)
    table_frame_budget_stages(res, out_dir)

    if not res:
        print(
            "\nAll tables except kernel_checks are stubs. Produce measurements with:\n"
            "  cvdyn2dgs experiments --out results --size small\n"
            "then re-run this script.",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
