def table_theory_rates(res: dict, out: Path) -> None:
    checks = res.get("theory_checks") or []
    by_name = {c.get("name", ""): c for c in checks if isinstance(c, dict)}

    def rate(key_frag: str, field: str, spec: str = ".2f") -> str:
        for name, c in by_name.items():
            if key_frag in name:
                return _fmt(_get(c, "measured", field), spec)
        return NM

    body = rf"""\begin{{table}}[htbp]
\centering\small
\caption{{이론이 예측하는 수렴률과 측정된 경험적 지수.}}
\label{{tab:theory-rates}}
\begin{{tabular}}{{@{{}}lccl@{{}}}}
\toprule
결과 & 예측 & 측정 & 비고 \\
\midrule
명제 \ref{{prop:normal-error}} $\sin\theta=O(\hmax^2)$
  & 2.0 & {rate('normal angular', 'slope')} & $\spacing$ 스윕 기울기 \\
보조정리 \ref{{lem:quadratic}} 이차 수축
  & 2.0 & {rate('quadratic', 'empirical_order')} & 잔차 이력 적합 \\
명제 \ref{{prop:interp-eikonal}} 식 \eqref{{eq:interp-eikonal}}
  & 0.0 & {rate('interpolation', 'worst_mean_abs_deviation')} & 측정 대 예측 편차 \\
명제 \ref{{prop:lowrank}} Eckart--Young
  & 0.0 & {rate('low-rank', 'worst_relative_deviation', '.2e')} & 상대 편차 \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    measured = any(rate(k, f) != NM for k, f in
                   [("normal angular", "slope"), ("quadratic", "empirical_order")])
    _write(out, "theory_rates", body, source="results/theory_checks.json", measured=measured)


